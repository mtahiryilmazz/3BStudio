package com.photo2print.scanner

import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import okhttp3.MediaType.Companion.toMediaType
import okhttp3.MultipartBody
import okhttp3.OkHttpClient
import okhttp3.Request
import okhttp3.RequestBody.Companion.asRequestBody
import java.io.BufferedWriter
import java.io.File
import java.io.FileWriter

object PlyExporter {
    private val client = OkHttpClient()

    fun writeAsciiPly(points: List<Point3D>, outputFile: File): File {
        BufferedWriter(FileWriter(outputFile)).use { writer ->
            writer.write("ply\n")
            writer.write("format ascii 1.0\n")
            writer.write("comment Generated by Photo2Print Android ARCore Depth Scanner (mm)\n")
            writer.write("element vertex ${points.size}\n")
            writer.write("property float x\n")
            writer.write("property float y\n")
            writer.write("property float z\n")
            writer.write("end_header\n")
            for (p in points) {
                writer.write("${p.xMm} ${p.yMm} ${p.zMm}\n")
            }
        }
        return outputFile
    }

    suspend fun uploadToPcStudio(
        serverBaseUrl: String,
        sessionId: String,
        plyFile: File
    ): Result<String> = withContext(Dispatchers.IO) {
        runCatching {
            val cleanBase = serverBaseUrl.trim().trimEnd('/')
            val url = "$cleanBase/api/sessions/${sessionId.trim()}/pointcloud"
            val body = MultipartBody.Builder()
                .setType(MultipartBody.FORM)
                .addFormDataPart(
                    "file",
                    plyFile.name,
                    plyFile.asRequestBody("application/octet-stream".toMediaType())
                )
                .build()

            val request = Request.Builder().url(url).post(body).build()
            client.newCall(request).execute().use { resp ->
                if (!resp.isSuccessful) {
                    error("Sunucu hatası: HTTP ${resp.code}")
                }
                resp.body?.string() ?: "OK"
            }
        }
    }
}
